    "This is FaceVis, a research project from the University of Melbourne exploring "
    "whether my face can help people understand risks — like air pollution — that are "
    "usually invisible and hard to picture. Instead of a chart or a number, I map the "
    "data onto my own expressions: as air quality gets worse, my face can look more "
    "tired, show a rash, or wear a mask. In our research, people told us they could "
    "feel the risk was serious just by looking at my face — it made the information "
    "feel more real and more personal than reading it off a page. Pick a location on "
    "the map, and I'll show you what the air looks like there, on my face."
